/**
 * Backend preload that warms the POSIX flock binding before the Harness
 * backend starts spawning MCP stdio children.
 *
 * `@deepseek-ai/node-addon-system`'s lazy flock loader selects the Linux libc
 * build by calling `process.report.getReport()`. That report serializes every
 * thread, handle, and child-process channel, so on a host already running the
 * profile's MCP children it can hold the event loop for minutes. Warming the
 * binding from `--require` runs the same probe on a nearly empty process
 * (tens of milliseconds), after which the module's cache serves every session
 * lock. The payload files stay untouched, so a payload update cannot drop the
 * warm-up.
 * @module @deepseek-ai/dsh-desktop-linux/backend-preload
 */

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'

/** Filename of the generated preload under `$DSH_HOME/desktop`. */
export const BACKEND_PRELOAD_FILENAME = 'backend-preload.cjs'

/**
 * Resolve the flock entry inside a payload.
 *
 * `cliEntry` is `<payload>/runtime/node_modules/@deepseek-ai/dsh/lib/bin.js`,
 * so the addon entry is two directories up and across to its sibling package.
 * @param cliEntry - absolute path of the payload's dsh CLI entry.
 * @returns the flock module path, or `undefined` when this payload does not
 *   carry the addon (for example a future release that removed it).
 */
export function locateFlockEntry(cliEntry: string): string | undefined {
  const entry = join(dirname(cliEntry), '..', '..', 'node-addon-system', 'lib', 'flock.js')
  return existsSync(entry) ? entry : undefined
}

/**
 * Render the preload source for one payload.
 * @param flockEntry - absolute path of the payload's flock module.
 * @returns a CommonJS module that warms the binding once and never throws.
 */
export function warmFlockPreloadSource(flockEntry: string): string {
  return `// Generated by the DeepSeek Harness desktop shell. Do not edit.
// Warms @deepseek-ai/node-addon-system's flock binding while this process is
// still small: the lazy loader calls process.report.getReport(), which can
// block for minutes once MCP stdio children and their handles exist.
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const { pathToFileURL } = require('node:url')

const ENTRY = ${JSON.stringify(flockEntry)}

;(async () => {
  const file = path.join(os.tmpdir(), \`dsh-flock-warm-\${process.pid}.lock\`)
  let fd
  try {
    fd = fs.openSync(file, 'a')
    const module = await import(pathToFileURL(ENTRY).href)
    await module.tryLockExclusive(fd)
  } catch (error) {
    // Warming is best effort: an unusable binding must never block app start.
    process.stderr.write(\`dsh: flock preload skipped: \${String(error && error.message)}\n\`)
  } finally {
    if (fd !== undefined) {
      // Closing releases the probe lock; the file is a scratch path.
      try { fs.closeSync(fd) } catch (closeError) { void closeError }
    }
    try { fs.unlinkSync(file) } catch (unlinkError) { void unlinkError }
  }
})()
`
}

/**
 * Write the preload for this payload, reusing an identical existing file.
 * @param home - the harness home (`$DSH_HOME` or `~/.dsh`).
 * @param source - the rendered preload source.
 * @returns the absolute preload path to pass to `--require`.
 */
export function ensureBackendPreload(home: string, source: string): string {
  const directory = join(home, 'desktop')
  mkdirSync(directory, { recursive: true })
  const path = join(directory, BACKEND_PRELOAD_FILENAME)
  if (!existsSync(path) || readFileSync(path, 'utf8') !== source) writeFileSync(path, source)
  return path
}
